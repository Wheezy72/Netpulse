-- NetPulse: per-device open-port inventory
--
-- Adds tables introduced in:
--   - app/models/device_port.py
--
-- Populated by the per-device deep scan (app/services/device_enrichment.py).
-- Rows describe the currently observed state for a device, so a later
-- successful scan replaces the previous set rather than accumulating.
--
-- PostgreSQL.

BEGIN;

CREATE TABLE IF NOT EXISTS device_ports (
    id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_id  INTEGER NOT NULL,
    port       INTEGER NOT NULL,
    protocol   VARCHAR(8) NOT NULL DEFAULT 'tcp',
    state      VARCHAR(24) NULL,
    service    VARCHAR(64) NULL,
    product    VARCHAR(128) NULL,
    version    VARCHAR(64) NULL,
    extra_info VARCHAR(255) NULL,
    banner     TEXT NULL,
    first_seen TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
    last_seen  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),

    CONSTRAINT fk_device_ports_device_id FOREIGN KEY (device_id) REFERENCES devices(id) ON DELETE CASCADE,
    CONSTRAINT uq_device_ports_device_port_proto UNIQUE (device_id, port, protocol)
);

CREATE INDEX IF NOT EXISTS ix_device_ports_device_id ON device_ports (device_id);
CREATE INDEX IF NOT EXISTS ix_device_ports_port ON device_ports (port);

COMMIT;
